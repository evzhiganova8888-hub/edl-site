def get_video_script(segment: str | None, stage: str | None) -> dict:
    """Возвращает шаблон сценария или общий дженерик."""
    seg = segment or "other"
    st = stage or "team"
    by_stage = VIDEO_SCRIPTS.get(seg, VIDEO_SCRIPTS["other"])
    return by_stage.get(st, VIDEO_SCRIPTS["other"]["team"])


def all_scripts_count() -> int:
    """Для теста — должно быть 7 сегментов × 4 стадии = 28 (6 канонических + other)."""
    return sum(len(stages) for stages in VIDEO_SCRIPTS.values())
