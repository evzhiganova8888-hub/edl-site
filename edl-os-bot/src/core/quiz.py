def total_score(answers: dict[str, int]) -> int:
    """Сумма баллов из ответов, нормированная к 0–100."""
    raw = sum(answers.get(q.key, 0) for q in QUIZ_QUESTIONS)
    max_raw = 10 * len(QUIZ_QUESTIONS)
    return int(round(raw * 100 / max_raw))


def layer_scores(answers: dict[str, int]) -> dict[str, int]:
    """Балл по каждому слою (0–30)."""
    out = {"strategy": 0, "sales": 0, "operations": 0, "finance": 0}
    for q in QUIZ_QUESTIONS:
        out[q.layer] += answers.get(q.key, 0)
    return out


def recommendation(score: int) -> tuple[str, str]:
    """Возвращает (product_code, текст рекомендации) по баллу."""
    if score <= 40:
        return (
            "audit",
            "Рекомендую начать с Бизнес-чекапа за 9 000 ₽ — он покажет, где у вас "
            "сейчас утечки, и даст 3 действия на неделю + план на 90 дней. "
            "С гарантией возврата 100% в течение 14 дней.",
        )
    if score <= 70:
        return (
            "diagnostic",
            "Похоже, вы готовы к Диагностике (25 000 ₽, 3–5 дней). Это глубокое "
            "погружение в данные и спецификация Спринта — будем понимать, "
            "что именно внедрять. Если сомневаетесь — можно сначала Чекап за 9 000 ₽.",
        )
    return (
        "sprint",
        "У вас зрелая инфраструктура. Можно сразу обсуждать Спринт "
        "(135 / 185 / 260 тыс. ₽, 4 недели). Внедрим систему: данные, "
        "Telegram-бот, ИИ-ассистент. Стартуем 1–2 потока в месяц — "
        "запишу в лист ожидания.",
    )


